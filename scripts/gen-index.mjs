// Regenerates src/index.ts so every file in src/components/ui is exported.
// Run after `npx shadcn@latest add <component>`:  npm run gen:index
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { headerFor } from "./license-headers.mjs"

const OUT = "src/index.ts"

const files = (dir) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /\.tsx?$/.test(f) && !f.endsWith(".d.ts"))
        .map((f) => f.replace(/\.tsx?$/, ""))
        .sort()
    : []

// Keep the year the file was first stamped so regenerating it doesn't churn the header.
const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
const year = Number(previous.match(/Copyright (\d{4}) /)?.[1]) || undefined

const modules = [
  "./lib/utils",
  ...files("src/hooks").map((f) => `./hooks/${f}`),
  ...files("src/components/ui").map((f) => `./components/ui/${f}`),
]

const body = [
  '"use client"',
  "",
  "// Auto-generated by scripts/gen-index.mjs. Do not edit by hand.",
  "// Compiled into dist/styles.css at build time (not injected at runtime).",
  'import "./styles/globals.css"',
  ...modules.map((m) => `export * from "${m}"`),
  "",
].join("\n")

writeFileSync(OUT, headerFor(OUT, year) + body)
console.log(`${OUT}: ${modules.length} modules exported`)
